/*
 * 16x16 status-bar icon font for the SSD1306 status strip.
 *
 * Eight glyphs in the 0x40..0x47 ('@'..'G') ASCII range -- easy to
 * remember and printable, so cfb_print(disp, "\x40\x45", ...) just works.
 *
 * Glyphs:
 *   0x40 (@)  battery   0 % fill
 *   0x41 (A)  battery  25 % fill
 *   0x42 (B)  battery  50 % fill
 *   0x43 (C)  battery  75 % fill
 *   0x44 (D)  battery 100 % fill
 *   0x45 (E)  Link (USB-connected indicator)
 *   0x46 (F)  Bluetooth
 *   0x47 (G)  REC dot
 *
 * Storage: VPACKED, MSB-first. CFB stores each glyph as
 * 2 * width = 32 bytes; layout is column-major where each pair of
 * bytes (top, bottom) covers the 16 vertical pixels of one column,
 * MSB = topmost row in that 8-pixel tile. Bytes were generated by
 * tools/convert (see commit message) from u8g2's BDF row-major hex
 * for the Open Iconic glyphs.
 *
 * Sources:
 *   - Bluetooth, REC dot, and chain-link adapted from u8g2's BDF
 *     fonts open_iconic_embedded_2x.bdf, open_iconic_play_2x.bdf,
 *     and open_iconic_www_2x.bdf (Open Iconic, SIL Open Font License,
 *     https://github.com/iconic/open-iconic).
 *   - Battery cells (5 fill levels) hand-rolled for this project;
 *     license is the same as the rest of pwr-logger.
 */

